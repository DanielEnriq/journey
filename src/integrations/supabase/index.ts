import { createClient, type SupabaseClient } from '@supabase/supabase-js';
import { config } from '../../config.js';
import type { Database } from './types.js';

/**
 * Supabase cloud backend: shared data (workspaces, rooms) lives in Postgres behind
 * row-level security; local-only data stays in SQLite (src/database/).
 *
 * Who you are is one Supabase user, whichever way you sign in (src/integrations/account): each
 * sign-in method is an identity linked to that user, so auth.uid() and everything RLS keys on it
 * stays the same. A Google session exchanges the Google ID token for a Supabase session on every
 * sign-in and launch (signInWithIdToken), kept in memory only. A GitHub session *is* a Supabase
 * session, from Supabase's GitHub OAuth; its refresh token is kept encrypted on this machine. If
 * the session goes away while signed in, getCloud() asks the account to reconnect.
 *
 * Schema: supabase/migrations/. Types: ./types.ts, generated by `pnpm cloud:types`; don't edit
 * it by hand. Column grants and RLS aren't reflected there: Update types list every column,
 * but only the columns granted in the migrations are writable.
 */

export type Cloud = SupabaseClient<Database>;

let client: Cloud | undefined;
let queue: Promise<unknown> = Promise.resolve();
let reconnect: (() => Promise<void>) | undefined;

/** Runs session changes one at a time, so a quick sign-in → sign-out applies in order. */
export function enqueue<T>(task: () => Promise<T>): Promise<T> {
  const run = queue.then(task);
  queue = run.catch(() => {});
  return run;
}

export function isCloudConfigured(): boolean {
  return Boolean(config.supabase.url && config.supabase.publishableKey);
}

function settings(): { url: string; publishableKey: string } {
  const { url, publishableKey } = config.supabase;
  if (!url || !publishableKey) {
    throw new Error('Supabase not configured — set SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY in .env');
  }
  return { url, publishableKey };
}

/** The app's one client, signed in or not. Most code wants getCloud(). */
export function cloud(): Cloud {
  const { url, publishableKey } = settings();
  client ??= createClient<Database>(url, publishableKey, {
    auth: { persistSession: false, autoRefreshToken: true, detectSessionInUrl: false },
  });
  return client;
}

/**
 * A client for one OAuth sign-in or link (PKCE, in memory, never refreshing on its own). Its session's
 * tokens go to cloud(), or it's dropped.
 */
export function authClient(): Cloud {
  const { url, publishableKey } = settings();
  return createClient<Database>(url, publishableKey, {
    auth: { flowType: 'pkce', persistSession: false, autoRefreshToken: false, detectSessionInUrl: false },
  });
}

/** How getCloud() gets a session back while someone is signed in; undefined while signed out. */
export function setReconnect(fn: (() => Promise<void>) | undefined) {
  reconnect = fn;
}

async function hasSession(supabase: Cloud): Promise<boolean> {
  const { data } = await supabase.auth.getSession(); // refreshes an expiring token first
  return Boolean(data.session);
}

/**
 * The signed-in Supabase client. Waits for an in-flight sign-in, reconnects if the user
 * is signed in but has no cloud session, and throws if signed out.
 */
export async function getCloud(): Promise<Cloud> {
  await queue;
  const supabase = cloud();
  if (await hasSession(supabase)) return supabase;
  if (reconnect) {
    await enqueue(async () => {
      if (reconnect && !(await hasSession(supabase))) await reconnect();
    });
  }
  if (!(await hasSession(supabase))) throw new Error('Not signed in to the cloud');
  return supabase;
}

/** Cloud user id (auth.uid()). For a Google session it isn't the local user id, which is the Google `sub`. */
export async function getCloudUserId(): Promise<string> {
  const { data } = await (await getCloud()).auth.getSession();
  return data.session!.user.id;
}

/** Leaves live rooms, then ends this device's session. Run it through enqueue(). */
export async function disconnectCloud() {
  // Leave live rooms first, while the session can still authorize the unsubscribe.
  await cloud().removeAllChannels();
  // scope 'local': end this device's session without signing the user out elsewhere.
  const { error } = await cloud().auth.signOut({ scope: 'local' });
  if (error) console.warn('[cloud] sign-out failed:', error.message);
}
